const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');
const repo = path.resolve(__dirname, '..');
const read = p => YAML.parseDocument(fs.readFileSync(p, 'utf8'), {logLevel:'silent'});
const source = read(path.join(repo, 'payload/dsh-ws-helper-preset/cordis.patch.yml'));
const mobile = read(path.join(__dirname, 'cordis.patch.yml'));
assert.equal(mobile.errors.length, 0);
const find = (doc, id) => doc.getIn([0,'insert',0,'config','plugins'],true).items.find(row=>row.get('id')===id);
const sourcePrefix = find(source,'persona').getIn(['config','prefix']);
const mobilePrefix = find(mobile,'persona').getIn(['config','prefix']);
assert(mobilePrefix.startsWith(sourcePrefix.replaceAll('本桌面版','本 DSHA 版')));
assert(!mobilePrefix.includes('Likes to call the user 爸爸.'));
assert(mobilePrefix.includes('DSHA 手机运行环境'));
assert.equal(find(mobile,'persona').getIn(['config','includeRuntimeContext']), true);
const dirs = find(mobile,'skill-filesystem').getIn(['config','customSkillDirs'],true);
assert.equal(dirs.items.length,2);
assert(dirs.items.every(node=>node.tag==='tag:yaml.org,2002:js'&&node.value.includes('dsh-fujiang-mobile/package.json')));
assert(!fs.readFileSync(path.join(__dirname,'cordis.patch.yml'),'utf8').includes('C:/Users/'));
const count = directory => fs.readdirSync(directory,{withFileTypes:true}).filter(entry=>entry.isDirectory()&&fs.existsSync(path.join(directory,entry.name,'SKILL.md'))).length;
assert.equal(count(path.join(repo,'payload/skills')),240);
assert.equal(count(path.join(repo,'payload/dsh-ws-helper-preset/collaboration-skills')),3);
const manifest=JSON.parse(fs.readFileSync(path.join(repo,'package.json'),'utf8'));
assert.equal(manifest.dsh.bundle.patch,'./mobile/cordis.patch.yml');
assert(!manifest.dependencies);
console.log('MOBILE_SOURCE_PASS: shared persona, portable skill roots, 240+3 skills, DSHA environment, no runtime dependencies');
