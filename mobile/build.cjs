// Generate the DSHA adapter from the shared preset; do not maintain a second persona.
const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');
const repo = path.resolve(__dirname, '..');
const doc = YAML.parseDocument(fs.readFileSync(path.join(repo, 'payload/dsh-ws-helper-preset/cordis.patch.yml'), 'utf8'));
if (doc.errors.length) throw doc.errors[0];
doc.setIn([0, 'insert', 0, 'id'], 'preset-ws-helper-mobile');
doc.setIn([0, 'insert', 0, 'config', 'description'], 'DSHA 工作助手：主动澄清与汇报、工具和子代理协作、Ubuntu/Android 环境指引、240 + 3 个技能。');
const plugins = doc.getIn([0, 'insert', 0, 'config', 'plugins'], true);
const persona = plugins.items.find(row => row.get('id') === 'persona');
const mobileGuide = fs.readFileSync(path.join(__dirname, 'environment.md'), 'utf8');
persona.setIn(['config', 'prefix'], persona.getIn(['config', 'prefix']).replaceAll('本桌面版', '本 DSHA 版') + '\n\n' + mobileGuide.trim());
persona.setIn(['config', 'includeRuntimeContext'], true);
const skills = plugins.items.find(row => row.get('id') === 'skill-filesystem');
const dirs = doc.createNode([]);
for (const subdir of ['payload/skills', 'payload/dsh-ws-helper-preset/collaboration-skills']) {
  const value = doc.createNode(`(() => { const p = process.getBuiltinModule('node:path'); const m = process.getBuiltinModule('node:module'); return p.join(p.dirname(m.createRequire(baseUrl).resolve('dsh-fujiang-mobile/package.json')), '${subdir}'); })()`);
  value.tag = 'tag:yaml.org,2002:js';
  dirs.items.push(value);
}
skills.setIn(['config', 'customSkillDirs'], dirs);
YAML.visit(doc, { Node(_key, node) { node.comment = undefined; node.commentBefore = undefined; } });
fs.writeFileSync(path.join(__dirname, 'cordis.patch.yml'), '# Generated by mobile/build.cjs from the shared preset.\n' + doc.toString({lineWidth: 0}));
console.log('Generated mobile/cordis.patch.yml');
