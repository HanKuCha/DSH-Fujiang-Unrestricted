const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');
const repo = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(repo, 'payload/dsh-ws-helper-preset/cordis.patch.yml'), 'utf8');
const doc = YAML.parseDocument(source.replaceAll('@local/dsh-ws-helper-preset', 'dsh-fujiang-mobile'));
if (doc.errors.length) throw doc.errors[0];
YAML.visit(doc, { Node(_key, node) { node.comment = undefined; node.commentBefore = undefined; } });
fs.writeFileSync(path.join(__dirname, 'cordis.patch.yml'), '# Generated from the shared Fujiang bundle.\n' + doc.toString({lineWidth:0}).replace(/^[ \t]+$/gm,''));
const client = fs.readFileSync(path.join(repo, 'payload/dsh-ws-helper-preset/upstream/lib/client.js'), 'utf8');
fs.writeFileSync(path.join(__dirname, 'client.js'), client.replace('id: "@local/dsh-ws-helper-preset"', 'id: "dsh-fujiang-mobile"'));
console.log('Generated DSHA bundle and client');
